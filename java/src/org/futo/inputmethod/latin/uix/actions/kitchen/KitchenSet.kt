/**
 * One Emoji Kitchen combination of an animal with another emoji.
 * Generated by tools/kitchen/fetch_kitchen.py from the emojikitchen.dev data set.
 */
data class KitchenEntry(
    val emoji: String,
    /** Official name of the partner emoji, e.g. "face with tears of joy" */
    val name: String,
    val alt: String,
    /** Lowercase search tags: name, aliases, Unicode names and emojikitchen.dev keywords */
    val keywords: List<String>,
    val file: String,
    /** Where Google hosts the image, for animals that aren't built in */
    val url: String
) {
    val nameWords: List<String> = name.lowercase().split(' ').filter { it.isNotEmpty() }
    val keywordWords: List<String> = keywords.flatMap { it.split(' ') }.filter { it.isNotEmpty() }.distinct()
}

/**
 * An animal the keyboard can be built around. Every Emoji Kitchen animal is ready; animals that
 * Emoji Kitchen doesn't have yet are listed as WIP and can't be picked.
 */
data class KitchenAnimal(
    val key: String,
    val name: String,
    val emoji: String,
    /** How many combinations it has */
    val count: Int,
    /** Images ship inside the app (the cow); the others download when picked */
    val builtIn: Boolean,
    val ready: Boolean = true,
    /** A picture for animals without an emoji, as an asset path */
    val picture: String? = null
)

object KitchenAnimals {
    private const val DEFAULT = "cow"

    // Animals without Emoji Kitchen combinations yet
    private val wip = listOf(
        KitchenAnimal("seal", "Seal", "🦭", 0, builtIn = false, ready = false),
        KitchenAnimal("manatee", "Manatee", "", 0, builtIn = false, ready = false,
            picture = "cow_kitchen/u1f42e_u1f41f.png"),
    )

    @Volatile private var cached: List<KitchenAnimal>? = null

    fun all(context: Context): List<KitchenAnimal> = cached ?: synchronized(this) {
        cached ?: run {
            val text = context.assets.open("kitchen/animals.json").bufferedReader().use { it.readText() }
            val ready = Json.parseToJsonElement(text).jsonArray.map {
                val o = it.jsonObject
                KitchenAnimal(
                    key = o["key"]!!.jsonPrimitive.content,
                    name = o["name"]!!.jsonPrimitive.content,
                    emoji = o["emoji"]!!.jsonPrimitive.content,
                    count = o["count"]!!.jsonPrimitive.int,
                    builtIn = o["builtIn"]!!.jsonPrimitive.boolean
                )
            }
            // the built-in animal first, then Emoji Kitchen's order, then the WIP ones
            (ready.filter { it.builtIn } + ready.filter { !it.builtIn } + wip).also { cached = it }
        }
    }

    fun ready(context: Context, key: String): KitchenAnimal? = all(context).firstOrNull { it.key == key && it.ready }

    /** The animal the user picked, or the cow if they haven't picked one */
    fun active(context: Context): KitchenAnimal =
        ready(context, context.getSetting(KitchenAnimalSetting)) ?: ready(context, DEFAULT)!!
}

/** The chosen animal's key; empty until the user has picked one */
val KitchenAnimalSetting = SettingsKey(stringPreferencesKey("kitchen_animal"), "")

/** When enabled, tapping an emoji in the regular emoji panel sends its animal combination instead */
val KitchenReplaceEmojiTaps = SettingsKey(booleanPreferencesKey("cow_kitchen_replace_emoji_taps"), true)

internal const val KITCHEN_MIME_TYPE = "image/png"
private const val USAGE_LIMIT = 64
private const val AVERAGE_IMAGE_BYTES = 11_000

/**
 * One animal's Emoji Kitchen combinations: an index in assets/kitchen/<animal>.json, with the
 * images either in the app's assets (built in) or downloaded to files/kitchen/<animal>/.
 * Images are handed to apps through the content provider at content://<app>.font/kitchen/<animal>/<file>.
 */
class KitchenSet private constructor(val animal: KitchenAnimal) {
    companion object {
        private val sets = mutableMapOf<String, KitchenSet>()

        fun of(animal: KitchenAnimal): KitchenSet = synchronized(sets) { sets.getOrPut(animal.key) { KitchenSet(animal) } }

        fun of(context: Context, key: String): KitchenSet? = KitchenAnimals.ready(context, key)?.let { of(it) }

        fun active(context: Context): KitchenSet = of(KitchenAnimals.active(context))
    }

    val key get() = animal.key

    /** Rough download size, for telling the user before they download */
    val approximateMegabytes: Int get() = maxOf(1, animal.count * AVERAGE_IMAGE_BYTES / 1_000_000)

    @Volatile private var entries: List<KitchenEntry>? = null
    private var byEmoji: Map<String, KitchenEntry> = emptyMap()
    private var byFile: Map<String, KitchenEntry> = emptyMap()

    private val thumbnails = object : LruCache<String, ImageBitmap>(16 * 1024 * 1024) {
        override fun sizeOf(key: String, value: ImageBitmap): Int = value.width * value.height * 4
    }

    // Emoji Kitchen and gemoji disagree on variation selectors, and combinations only exist for
    // the default skin tone, so both are stripped before matching
    private fun normalize(emoji: String): String = buildString {
        var i = 0
        while (i < emoji.length) {
            val cp = emoji.codePointAt(i)
            if (cp != 0xFE0F && cp !in 0x1F3FB..0x1F3FF) appendCodePoint(cp)
            i += Character.charCount(cp)
        }
    }

    fun getEntries(context: Context): List<KitchenEntry> = entries ?: synchronized(this) {
        entries ?: run {
            val text = context.assets.open("kitchen/$key.json").bufferedReader().use { it.readText() }
            val list = Json.parseToJsonElement(text).jsonArray.map {
                val obj = it.jsonObject
                KitchenEntry(
                    emoji = obj["emoji"]!!.jsonPrimitive.content,
                    name = obj["name"]?.jsonPrimitive?.content
                        ?: obj["description"]?.jsonPrimitive?.content?.replace('_', ' ') ?: "",
                    alt = obj["alt"]!!.jsonPrimitive.content,
                    keywords = obj["keywords"]?.jsonArray?.map { k -> k.jsonPrimitive.content } ?: listOf(),
                    file = obj["file"]!!.jsonPrimitive.content,
                    url = obj["url"]!!.jsonPrimitive.content
                )
            }
            byEmoji = list.associateBy { normalize(it.emoji) }
            byFile = list.associateBy { it.file }
            entries = list
            list
        }
    }

    /**
     * Every typed word must start some word of the emoji's name or tags, so "tears joy" and "cry"
     * both find 😂. Pasting the emoji itself works too. Name matches are listed first.
     */
    fun search(entries: List<KitchenEntry>, query: String): List<KitchenEntry> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return entries
        val words = q.split(' ').filter { it.isNotEmpty() }
        val qEmoji = normalize(query.trim())

        return entries.mapNotNull { e ->
            val score = when {
                normalize(e.emoji) == qEmoji || e.name == q -> 0
                // Whole words beat partial ones, so "cry" ranks 😭 above 🔮 (crystal ball)
                words.all { it in e.nameWords } -> 1
                words.all { it in e.keywordWords } -> 2
                words.all { w -> e.nameWords.any { it.startsWith(w) } } -> 3
                words.all { w -> e.keywordWords.any { it.startsWith(w) } } -> 4
                else -> return@mapNotNull null
            }
            e to score
        }.sortedBy { it.second }.map { it.first }
    }

    fun find(context: Context, emoji: String): KitchenEntry? {
        getEntries(context)
        return byEmoji[normalize(emoji)]
    }

    // ---- images ---------------------------------------------------------------------------------

    fun packDir(context: Context) = File(context.filesDir, "kitchen/$key")

    private fun completeMarker(context: Context) = File(packDir(context), ".complete")

    /** Whether the images are on the phone: built in, or the pack has finished downloading */
    fun isAvailable(context: Context): Boolean = animal.builtIn || completeMarker(context).exists()

    private fun open(context: Context, file: String): InputStream =
        if (animal.builtIn) context.assets.open("${key}_kitchen/$file") else File(packDir(context), file).inputStream()

    /**
     * A plain file the content provider can hand out. Built-in images are copied out of the assets
     * first; copies older than the installed APK are refreshed, so updated artwork replaces stale images.
     */
    fun getCachedFile(context: Context, fileName: String): File {
        getEntries(context)
        require(byFile.containsKey(fileName)) { "Unknown $key kitchen image $fileName" }
        if (!animal.builtIn) return File(packDir(context), fileName)

        val dir = File(context.cacheDir, "${key}_kitchen").apply { mkdirs() }
        val file = File(dir, fileName)
        if (!file.exists() || file.length() == 0L || file.lastModified() < apkUpdateTime(context)) {
            val tmp = File(dir, "$fileName.tmp")
            open(context, fileName).use { input ->
                tmp.outputStream().use { input.copyTo(it) }
            }
            file.delete()
            tmp.renameTo(file)
        }
        return file
    }

    private var apkUpdateTime: Long? = null
    private fun apkUpdateTime(context: Context): Long = apkUpdateTime ?: runCatching {
        context.packageManager.getPackageInfo(context.packageName, 0).lastUpdateTime
    }.getOrDefault(0L).also { apkUpdateTime = it }

    fun loadThumbnail(context: Context, entry: KitchenEntry): ImageBitmap? {
        thumbnails.get(entry.file)?.let { return it }
        val bitmap = runCatching {
            open(context, entry.file).use {
                BitmapFactory.decodeStream(it, null, BitmapFactory.Options().apply { inSampleSize = 4 })
            }
        }.getOrNull()?.asImageBitmap() ?: return null
        thumbnails.put(entry.file, bitmap)
        return bitmap
    }

    /** Full-resolution image for the press-and-hold preview */
    fun loadFull(context: Context, entry: KitchenEntry): ImageBitmap? =
        runCatching { open(context, entry.file).use { BitmapFactory.decodeStream(it) } }.getOrNull()?.asImageBitmap()

    fun send(manager: KeyboardManagerForAction, entry: KitchenEntry): Boolean {
        val uri = "content://${FONT_AUTHORITY}/kitchen/$key/${entry.file}".toUri()
        val sent = manager.typeUri(uri, listOf(KITCHEN_MIME_TYPE), true)
        if (sent) {
            val context = manager.getContext()
            manager.getLifecycleScope().launch { recordUse(context, entry.file) }
        }
        return sent
    }

    // ---- most used ------------------------------------------------------------------------------

    private val usageKey = stringPreferencesKey("${key}_kitchen_usage")

    // Stored as "file=count" pairs separated by ';', most used first
    private fun parseUsage(stored: String?): LinkedHashMap<String, Int> = LinkedHashMap<String, Int>().apply {
        stored?.split(';')?.forEach { pair ->
            val i = pair.lastIndexOf('=')
            if (i > 0) pair.substring(i + 1).toIntOrNull()?.let { put(pair.substring(0, i), it) }
        }
    }

    private suspend fun recordUse(context: Context, file: String) {
        if (context.isDeviceLocked) return
        context.dataStore.edit { ds ->
            val counts = parseUsage(ds[usageKey])
            // Re-inserted first, so among equal counts the most recently used wins
            val updated = linkedMapOf(file to (counts.remove(file) ?: 0) + 1).apply { putAll(counts) }
            ds[usageKey] = updated.entries.sortedByDescending { it.value }.take(USAGE_LIMIT)
                .joinToString(";") { "${it.key}=${it.value}" }
        }
    }

    /** The most often sent combinations, for the strip at the top of the panel */
    suspend fun mostUsed(context: Context, limit: Int): List<KitchenEntry> {
        if (context.isDeviceLocked) return emptyList()
        getEntries(context)
        return parseUsage(context.getSetting(usageKey, "")).keys.mapNotNull { byFile[it] }.take(limit)
    }

    internal fun markComplete(context: Context) {
        packDir(context).mkdirs()
        completeMarker(context).createNewFile()
    }
}

/** Sends the chosen animal's combinations in place of plain emojis */
object AnimalKitchen {
    /**
     * Called by the regular emoji panel. Returns true if the combination was sent, false if the
     * caller should type the plain emoji instead (disabled, no combination, pack not downloaded,
     * or the app can't take images).
     */
    fun tryReplaceEmoji(manager: KeyboardManagerForAction, emoji: EmojiItem): Boolean {
        val context = manager.getContext()
        if (emoji.category == "ASCII") return false
        if (!context.getSetting(KitchenReplaceEmojiTaps)) return false
        val set = KitchenSet.active(context)
        if (!set.isAvailable(context)) return false
        if (!manager.appSupportsImageInsertion(KITCHEN_MIME_TYPE, true)) return false

        val entry = set.find(context, emoji.emoji) ?: set.find(context, emoji.untoned) ?: return false
        return set.send(manager, entry)
    }
}

/** Downloads an animal's images from Google's Emoji Kitchen servers, once, so it then works offline */
object KitchenDownloads {
    sealed interface State {
        data class Running(val done: Int, val total: Int) : State
        data class Failed(val message: String) : State
    }

    /** Downloads in progress or failed, by animal; read from Compose so the UI follows along */
    val states = mutableStateMapOf<String, State>()

    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.IO)
    @Suppress("OPT_IN_USAGE")
    private val network = Dispatchers.IO.limitedParallelism(6)

    /** Some Android versions let the user switch off network access per app */
    fun hasNetworkPermission(context: Context): Boolean =
        context.checkSelfPermission(Manifest.permission.INTERNET) == PackageManager.PERMISSION_GRANTED

    fun start(context: Context, set: KitchenSet) {
        if (set.isAvailable(context) || states[set.key] is State.Running) return
        val app = context.applicationContext
        val key = set.key
        states[key] = State.Running(0, set.animal.count)
        scope.launch {
            try {
                val entries = set.getEntries(app)
                val dir = set.packDir(app).apply { mkdirs() }
                val done = AtomicInteger(0)
                coroutineScope {
                    entries.map { entry ->
                        async(network) {
                            fetch(entry.url, File(dir, entry.file))
                            val n = done.incrementAndGet()
                            if (n % 8 == 0 || n == entries.size) {
                                withContext(Dispatchers.Main) { states[key] = State.Running(n, entries.size) }
                            }
                        }
                    }.awaitAll()
                }
                set.markComplete(app)
                withContext(Dispatchers.Main) { states.remove(key) }
            } catch (e: Exception) {
                withContext(Dispatchers.Main) { states[key] = State.Failed(e.message ?: e.javaClass.simpleName) }
            }
        }
    }

    private fun fetch(url: String, dest: File) {
        if (dest.exists() && dest.length() > 0) return
        val conn = URL(url).openConnection() as HttpURLConnection
        conn.connectTimeout = 15_000
        conn.readTimeout = 30_000
        conn.setRequestProperty("User-Agent", "Mozilla/5.0")
        try {
            if (conn.responseCode != 200) throw Exception("HTTP ${conn.responseCode}")
            val tmp = File(dest.parentFile, "${dest.name}.tmp")
            conn.inputStream.use { input -> tmp.outputStream().use { input.copyTo(it) } }
            tmp.renameTo(dest)
        } finally {
            conn.disconnect()
        }
    }
}
